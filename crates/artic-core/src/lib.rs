//! The foundations of artic: reactive values, properties, and the node tree.
//!
//! - [`reactive`]: signals, memos, effects and scopes, the only change-propagation mechanism.
//! - [`property`]: [`Property`](property::Property), a reactive value that several sources write at
//!   once, ranked by precedence, with metadata for invalidation and inheritance.
//! - [`tree`]: [`UiTree`](tree::UiTree), which owns every node and links it into a logical and
//!   a visual tree, with per-node dirty flags.
//! - [`Object`]: the trait every node type implements.
//! - [`event`]: [`Event`](event::Event), the field type that declares a node's events.
//! - [`input`]: [`InputEvent`](input::InputEvent), the input an element receives.
//! - [`dispatcher`]: [`Dispatcher`](dispatcher::Dispatcher), the UI thread's task queue, which flushes
//!   effects after each task.
//! - [`error`]: [`Chain`](error::Chain), which shows an error to a person with each of its causes.
//! - [`ToRust`]: a value that writes the Rust expression that builds it, into a [`RustExpr`], for
//!   code generated at build time.
//!
//! The `testing` feature adds `reactive::assert_no_reactive_leaks` for leak checks in other crates'
//! tests.

pub(crate) mod arena;
pub mod dispatcher;
pub mod error;
